// WHISKY LOADSCREEN — Local MP4 playback only. FiveM CEF-compatible.
// No YouTube, WASM, remote scripts, or backdrop-filter. No Discord secrets in NUI.
(function () {
    'use strict';

    var video = document.getElementById('background-video');
    var slider = document.getElementById('volume-slider');
    var volumeValue = document.getElementById('volume-value');
    var smallWave = document.getElementById('sound-wave-small');
    var largeWave = document.getElementById('sound-wave-large');
    var mutedLine = document.getElementById('muted-line');
    var prevButton = document.getElementById('previous-video');
    var nextButton = document.getElementById('next-video');
    var playButton = document.getElementById('toggle-play');
    var playIcon = document.getElementById('play-icon');
    var pauseIcon = document.getElementById('pause-icon');
    var titleLabel = document.getElementById('current-video-title');
    var counterLabel = document.getElementById('media-counter');
    var statusLabel = document.getElementById('media-status');
    var staffPanel = document.getElementById('staff-panel');
    var staffList = document.getElementById('staff-list');
    var serverName = document.getElementById('server-name');
    var playerCounter = document.getElementById('player-counter');
    var playerCountText = document.getElementById('player-count-text');
    var onlineRoster = document.getElementById('online-roster');
    var rosterList = document.getElementById('online-roster-list');
    var rosterSource = document.getElementById('roster-source');
    var rosterFooter = document.getElementById('online-roster-footer');
    var progressStatus = document.getElementById('progress-status');
    var progressPercent = document.getElementById('progress-percent');
    var progressTrack = document.getElementById('progress-track');
    var progressFill = document.getElementById('progress-fill');
    var settingsButton = document.getElementById('settings-toggle');
    var settingsPanel = document.getElementById('settings-panel');
    var settingsClose = document.getElementById('settings-close');
    var streamerToggle = document.getElementById('streamer-toggle');

    var STORAGE_KEY = 'whisky_loadscreen_streamer_v1';
    var streamerMode = false;
    // Staff always comes from the server-configured Discord staff service.
    // Browser previews use the public snapshot generated by that service;
    // FiveM uses the latest server handover. The online roster is unrelated.
    var fallbackStaff = [
        { slot: 1, name: 'Owner', role: 'OWNER', avatar: null, verified: false },
        { slot: 2, name: 'Co-Owner', role: 'CO-OWNER', avatar: null, verified: false },
        { slot: 3, name: 'Developer', role: 'DEVELOPER', avatar: null, verified: false },
        { slot: 4, name: 'Management', role: 'MANAGEMENT', avatar: null, verified: false }
    ];
    var staffPayloadReceived = false;

    function sanitizeStaffList(members) {
        if (!Array.isArray(members)) return [];
        var cleaned = [];
        members.slice(0, 16).forEach(function (member, index) {
            if (!member || typeof member !== 'object') return;
            cleaned.push({
                slot: Number(member.slot) > 0 ? Number(member.slot) : index + 1,
                name: String(member.name || 'Staff Member').slice(0, 48),
                role: String(member.role || 'STAFF').slice(0, 32),
                avatar: safeAvatar(member.avatar),
                verified: member.verified === true || (!!member.avatar && member.verified !== false)
            });
        });
        return cleaned;
    }

    var snapshotStaff = sanitizeStaffList(window.WhiskyStaffSnapshot);
    var knownStaff = snapshotStaff.length ? snapshotStaff : fallbackStaff;

    var knownPlayers = [];
    var rosterReady = false;
    var rosterDefaultApplied = false;
    var rosterShowIds = true;
    var rosterMode = 'framework';
    var rosterTotalCount = 0;

    // localStorage is per-client browser storage; failures must not break loading.
    try { streamerMode = localStorage.getItem(STORAGE_KEY) === 'true'; } catch (ignored) {}


    var config = window.WhiskyMediaConfig || {};
    var playlist = [];
    var activeIndex = -1;
    var wantedPlaying = true;
    var failedIndices = {};
    var volume = Number(config.defaultVolume);
    if (!isFinite(volume)) volume = 35;
    volume = Math.min(100, Math.max(0, Math.round(volume)));

    // Only load locally bundled MP4s; no remote embeds or external dependencies.
    if (Array.isArray(config.playlist)) {
        config.playlist.forEach(function (item) {
            if (!item || typeof item.src !== 'string') return;
            var path = item.src.trim();
            if (!/^assets\/(?:[a-zA-Z0-9 _-]+\/)*[a-zA-Z0-9 _.-]+\.mp4$/i.test(path) || path.indexOf('..') !== -1) {
                console.warn('[Whisky Loadscreen] Skipped invalid MP4 path:', path);
                return;
            }
            playlist.push({
                src: path,
                title: typeof item.title === 'string' && item.title.trim()
                    ? item.title.trim().slice(0, 80) : 'Now Playing'
            });
        });
    }
    if (!playlist.length) {
        playlist.push({ src: 'assets/background.mp4', title: 'Welcome to the City' });
    }

    function status(message) {
        statusLabel.textContent = message || '';
        statusLabel.hidden = !message;
    }

    function updatePlayButton() {
        playIcon.hidden = wantedPlaying;
        pauseIcon.hidden = !wantedPlaying;
        var label = wantedPlaying ? 'Pause' : 'Play';
        playButton.title = label;
        playButton.setAttribute('aria-label', label);
    }

    function applyVolume(nextVolume) {
        volume = Math.min(100, Math.max(0, Number(nextVolume) || 0));
        slider.value = String(volume);
        slider.style.setProperty('--fill', volume + '%');
        volumeValue.textContent = volume + '%';
        smallWave.style.display = volume === 0 ? 'none' : '';
        largeWave.style.display = volume > 45 ? '' : 'none';
        mutedLine.style.display = volume === 0 ? '' : 'none';
        video.volume = volume / 100;
        video.muted = streamerMode || volume === 0;
        slider.disabled = streamerMode;
        // The user's chosen volume is kept for when Streamer Mode is disabled.
        volumeValue.textContent = streamerMode ? 'MUTED' : volume + '%';
    }

    function attemptPlay() {
        if (!wantedPlaying) return;
        var result;
        try { result = video.play(); } catch (error) { result = Promise.reject(error); }
        if (result && typeof result.catch === 'function') {
            result.catch(function () {
                if (!wantedPlaying) return;
                // CEF/browser autoplay may require muted playback initially.
                video.muted = true;
                var retry;
                try { retry = video.play(); } catch (error) { retry = Promise.reject(error); }
                if (retry && typeof retry.catch === 'function') {
                    retry.catch(function () {
                        wantedPlaying = false;
                        updatePlayButton();
                        status('Press Play to start the video');
                    });
                }
            });
        }
    }

    function selectVideo(index) {
        if (index < 0 || index >= playlist.length) return;
        activeIndex = index;
        wantedPlaying = true;
        status('');
        updatePlayButton();
        var item = playlist[activeIndex];
        titleLabel.textContent = item.title;
        counterLabel.textContent = (activeIndex + 1) + ' / ' + playlist.length;
        prevButton.disabled = playlist.length < 2;
        nextButton.disabled = playlist.length < 2;
        video.pause();
        video.src = item.src;
        video.load();
        applyVolume(volume);
        attemptPlay();
    }

    function navigation(direction) {
        if (playlist.length < 2) return;
        // Manual navigation lets you retry a previously missing video.
        failedIndices = {};
        selectVideo((activeIndex + direction + playlist.length) % playlist.length);
    }

    function onEnded() {
        if (config.autoNext === false) {
            wantedPlaying = false;
            updatePlayButton();
            return;
        }
        var index = activeIndex + 1;
        if (index >= playlist.length) {
            if (config.loopPlaylist === false) {
                wantedPlaying = false;
                updatePlayButton();
                return;
            }
            index = 0;
        }
        // Single-video playlists can repeat using the same player.
        if (index === activeIndex) {
            video.currentTime = 0;
            attemptPlay();
        } else selectVideo(index);
    }

    function onMediaError() {
        // If a source is missing, try another unfailed MP4 rather than looping forever.
        failedIndices[activeIndex] = true;
        for (var step = 1; step < playlist.length; step++) {
            var candidate = (activeIndex + step) % playlist.length;
            if (!failedIndices[candidate]) {
                console.warn('[Whisky Loadscreen] MP4 failed; trying the next video');
                selectVideo(candidate);
                return;
            }
        }
        wantedPlaying = false;
        updatePlayButton();
        status('Could not load MP4 — check html/assets/ and media_config.js');
    }

    prevButton.addEventListener('click', function () { navigation(-1); });
    nextButton.addEventListener('click', function () { navigation(1); });
    playButton.addEventListener('click', function () {
        wantedPlaying = !wantedPlaying;
        if (wantedPlaying) {
            status('');
            applyVolume(volume);
            attemptPlay();
        } else video.pause();
        updatePlayButton();
    });
    slider.addEventListener('input', function () {
        applyVolume(slider.value);
        if (wantedPlaying && video.paused) attemptPlay();
    });
    video.addEventListener('ended', onEnded);
    video.addEventListener('error', onMediaError);
    video.addEventListener('canplay', function () {
        if (wantedPlaying && video.paused) attemptPlay();
    });

    applyVolume(volume);
    selectVideo(0);

    function safeAvatar(url) {
        return typeof url === 'string' && /^https:\/\/cdn\.discordapp\.com\//.test(url)
            ? url : null;
    }

    function textNode(tag, className, text) {
        var el = document.createElement(tag);
        el.className = className;
        el.textContent = text;
        return el;
    }

    function makeStaffCard(member) {
        // Streamer Mode redacts both the visible name and downloaded avatar.
        var name = streamerMode ? 'Staff Member' : String(member.name || 'Staff Member').slice(0, 48);
        var role = String(member.role || 'STAFF').slice(0, 32);
        var card = document.createElement('div');
        card.className = 'staff-card';
        var avatarFrame = document.createElement('div');
        avatarFrame.className = 'staff-avatar';
        var initials = textNode('span', 'staff-avatar-initial', (name.trim().charAt(0) || '?').toUpperCase());
        avatarFrame.appendChild(initials);
        var avatarUrl = streamerMode ? null : safeAvatar(member.avatar);
        if (avatarUrl) {
            var img = document.createElement('img');
            img.alt = '';
            img.loading = 'eager';
            img.referrerPolicy = 'no-referrer';
            img.src = avatarUrl;
            img.addEventListener('error', function () {
                if (img.parentNode) img.parentNode.removeChild(img);
            });
            avatarFrame.appendChild(img);
        }
        card.appendChild(avatarFrame);
        var identity = document.createElement('div');
        identity.className = 'staff-identity';
        identity.appendChild(textNode('div', 'staff-name', name));
        identity.appendChild(textNode('div', 'staff-role', role));
        card.appendChild(identity);
        var indicator = document.createElement('span');
        indicator.className = 'staff-card-dot';
        indicator.setAttribute('aria-hidden', 'true');
        card.appendChild(indicator);
        return card;
    }

    function renderStaff(members) {
        // Configure staff ONCE from StaffDiscord.Members on the server.
        // Incoming player-roster data must never change these cards.
        // A fresh handover is authoritative; an unverified fallback cannot
        // replace a previously fetched profile for the same slot/rank.
        if (Array.isArray(members)) {
            var incoming = sanitizeStaffList(members);
            if (incoming.length) {
                var oldBySlot = {};
                knownStaff.forEach(function (m) { oldBySlot[m.slot] = m; });
                knownStaff = incoming.map(function (member) {
                    var prior = oldBySlot[member.slot];
                    if (!member.verified && prior && prior.verified &&
                            prior.role === member.role) return prior;
                    return member;
                });
            }
        }
        staffList.textContent = '';
        (knownStaff.length ? knownStaff : fallbackStaff).forEach(function (member) {
            staffList.appendChild(makeStaffCard(member));
        });
        staffPanel.removeAttribute('hidden');
    }

    function setRosterOpen(open) {
        open = !!open && rosterReady;
        onlineRoster.hidden = !open;
        playerCounter.setAttribute('aria-expanded', open ? 'true' : 'false');
        if (open) {
            settingsPanel.hidden = true;
            settingsButton.setAttribute('aria-expanded', 'false');
        }
    }

    function renderRoster() {
        rosterList.textContent = '';
        rosterSource.textContent = rosterMode === 'discord' ? 'DISCORD / FALLBACK' :
            rosterMode === 'fivem' ? 'FIVEM NAMES' : 'CHARACTER NAMES';
        if (!knownPlayers.length) {
            rosterList.appendChild(textNode('div', 'online-roster-empty',
                rosterTotalCount === 0 ? 'No players are online' : 'Roster unavailable'));
        }
        knownPlayers.forEach(function (player, index) {
            if (!player || typeof player !== 'object') return;
            var id = Number(player.id);
            var name = streamerMode ? 'Player ' + String(index + 1).padStart(2, '0') :
                String(player.name || 'Player').slice(0, 56);
            var row = document.createElement('div');
            row.className = 'online-player-row';
            var dot = document.createElement('span');
            dot.className = 'online-player-dot';
            dot.setAttribute('aria-hidden', 'true');
            row.appendChild(dot);
            row.appendChild(textNode('span', 'online-player-name', name));
            if (rosterShowIds && !streamerMode && Number.isInteger(id) && id >= 0) {
                row.appendChild(textNode('span', 'online-player-id', '#' + id));
            }
            rosterList.appendChild(row);
        });
        var missing = Math.max(0, rosterTotalCount - knownPlayers.length);
        rosterFooter.textContent = missing ? '+' + missing + ' more online • Connection snapshot' :
            'Online at the time you connected';
    }

    playerCounter.addEventListener('click', function () {
        setRosterOpen(onlineRoster.hidden);
    });

    function setSettingsOpen(open) {
        if (open) setRosterOpen(false);
        settingsPanel.hidden = !open;
        settingsButton.setAttribute('aria-expanded', open ? 'true' : 'false');
    }

    function setStreamerMode(enabled, persist) {
        streamerMode = !!enabled;
        streamerToggle.checked = streamerMode;
        document.body.classList.toggle('streamer-mode', streamerMode);
        applyVolume(volume);
        // Remove avatar elements from the DOM when switching into Streamer Mode.
        renderStaff();
        renderRoster();
        if (persist) {
            try { localStorage.setItem(STORAGE_KEY, String(streamerMode)); } catch (ignored) {}
        }
    }

    settingsButton.addEventListener('click', function () {
        setSettingsOpen(settingsPanel.hidden);
    });
    settingsClose.addEventListener('click', function () { setSettingsOpen(false); });
    streamerToggle.addEventListener('change', function () {
        setStreamerMode(streamerToggle.checked, true);
    });
    document.addEventListener('keydown', function (event) {
        if (event.key === 'Escape') { setSettingsOpen(false); setRosterOpen(false); }
    });
    document.addEventListener('click', function (event) {
        if (!settingsPanel.hidden && !settingsPanel.contains(event.target) &&
                !settingsButton.contains(event.target)) setSettingsOpen(false);
        if (!onlineRoster.hidden && !onlineRoster.contains(event.target) &&
                !playerCounter.contains(event.target)) setRosterOpen(false);
    });
    setStreamerMode(streamerMode, false);

    // FiveM sends a real fraction (0..1). Never use an artificial progress timer.
    window.addEventListener('message', function (event) {
        var data = event && event.data;
        if (!data || data.eventName !== 'loadProgress') return;
        if (typeof data.loadFraction !== 'number' || !isFinite(data.loadFraction)) return;
        var fraction = Math.min(1, Math.max(0, data.loadFraction));
        var percent = Math.round(fraction * 100);
        progressStatus.textContent = 'LOADING GAME ASSETS';
        progressPercent.textContent = percent + '%';
        progressFill.style.width = (fraction * 100) + '%';
        progressTrack.setAttribute('aria-valuenow', String(percent));
        progressTrack.removeAttribute('aria-valuetext');
    });

    // FiveM provides the population once when the player connects. This is
    // the actual GetPlayers() count, not a fake timer or a hardcoded number.
    // Some FiveM builds exposed nuiHandoverData as a JSON string; also, it can
    // initially contain only serverAddress before the resource data arrives.
    var populationReceived = false;
    var handoverRawSeen = null;

    function validCount(number) {
        if (typeof number === 'string' && /^\d{1,7}$/.test(number.trim())) {
            number = Number(number);
        }
        return typeof number === 'number' && isFinite(number) &&
            number >= 0 && Math.floor(number) === number ? number : null;
    }

    function parseHandover(raw) {
        if (typeof raw === 'string') {
            try { raw = JSON.parse(raw); }
            catch (ignored) { return null; }
        }
        return raw && typeof raw === 'object' && !Array.isArray(raw) ? raw : null;
    }

    function applyHandover(data) {
        var info = data.whiskyServer;
        if (info && typeof info === 'object') {
            if (typeof info.name === 'string' && info.name.trim()) {
                var name = info.name.trim().slice(0, 120);
                serverName.textContent = name;
                document.title = name + ' | Loading';
            }
            var count = validCount(info.players);
            if (count !== null) { // 0 is a legitimate empty-server count.
                var max = validCount(info.maxPlayers);
                playerCountText.textContent = max === null || max === 0
                    ? count + ' PLAYERS ONLINE'
                    : count + ' / ' + max + ' PLAYERS ONLINE';
                playerCounter.classList.add('is-ready');
                rosterTotalCount = count;
                populationReceived = true;
            }
        }
        if (data.whiskyStaff && Array.isArray(data.whiskyStaff.members)) {
            staffPayloadReceived = true;
            renderStaff(data.whiskyStaff.members);
        }
        if (data.whiskyPlayers && typeof data.whiskyPlayers === 'object') {
            var roster = data.whiskyPlayers;
            rosterReady = roster.enabled === true && Array.isArray(roster.members);
            rosterShowIds = roster.showIds !== false;
            rosterMode = ['discord', 'framework', 'fivem'].indexOf(roster.mode) !== -1 ? roster.mode : 'framework';
            knownPlayers = rosterReady ? roster.members.slice(0, 256) : [];
            if (rosterReady) {
                playerCounter.disabled = false;
                if (!rosterDefaultApplied) {
                    rosterDefaultApplied = true;
                    setRosterOpen(roster.defaultOpen === true);
                }
            } else {
                playerCounter.disabled = true;
                setRosterOpen(false);
            }
            renderRoster();
        }
    }

    function pollHandover() {
        var raw = window.nuiHandoverData;
        var data = parseHandover(raw);
        if (!data) return;
        // Re-parse only when the value changes. The main bug in v1.6 was
        // stopping the polling just because *any* object existed, including
        // {serverAddress: '...'} without whiskyServer.players.
        // If handover is being filled in-place, keep checking until *both*
        // population and staff data have arrived. Avoid unnecessary re-renders.
        if (raw === handoverRawSeen && populationReceived && staffPayloadReceived) return;
        if (raw === handoverRawSeen && !data.whiskyStaff && !data.whiskyServer) return;
        handoverRawSeen = raw;
        applyHandover(data);
    }

    renderStaff(); // Server-generated snapshot (or fallback), regardless of player roster.
    pollHandover();
    if (!populationReceived || !staffPayloadReceived) {
        var checks = 0;
        var handoverCheck = setInterval(function () {
            pollHandover();
            if ((populationReceived && staffPayloadReceived) || ++checks >= 400) { // Up to ~120 seconds.
                clearInterval(handoverCheck);
                if (!populationReceived) {
                    playerCountText.textContent = 'COUNT UNAVAILABLE';
                    console.warn('[Whisky Loadscreen] No player count in FiveM handover. Ensure server/handover.lua runs and check other resources using deferrals.handover.');
                }
                if (!staffPayloadReceived) {
                    console.warn('[Whisky Loadscreen] Staff handover unavailable: keeping last-known staff cards visible.');
                }
            }
        }, 300);
    }
})();
